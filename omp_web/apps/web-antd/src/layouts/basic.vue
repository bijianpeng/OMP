    <!-- 全局环境切换器：header-right-N 插槽按数字排序，1 位于内置部件
         （REFERENCE_VALUE=100 起）之前、user-dropdown 之前 -->
    <template #header-right-1>
      <EnvSwitcher />
    </template>
    <!-- 全局搜索图标按钮：内置输入框形态部件已在上方 updatePreferences 关闭，
         搜索弹窗与 Ctrl+K 快捷键由该组件内隐藏形态的 GlobalSearch 承载 -->
    <template #header-right-2>
      <GlobalSearchButton />
    </template>
    <template #user-dropdown>
      <UserDropdown
        :avatar
        :menus
        :text="userStore.userInfo?.realName"
        @clear-preferences-and-logout="handleLogout"
        @logout="handleLogout"
      />
    </template>
    <template #notification>
      <Notification
        :dot="showDot"
        :notifications="notifications"
        @clear="handleNoticeClear"
        @read="(item) => item.id && markRead(item.id)"
        @remove="(item) => item.id && remove(item.id)"
        @make-all="handleMakeAll"
        @on-click="handleClick"
        @view-all="viewAll"
      />
    </template>
    <template #extra>
      <AuthenticationLoginExpiredModal
        v-model:open="accessStore.loginExpired"
        :avatar
      >
        <LoginForm />
      </AuthenticationLoginExpiredModal>
      <ChangePasswordModal ref="passwordModalRef" />
    </template>
    <template #lock-screen>
      <LockScreen :avatar @to-login="handleLogout" />
    </template>
  </BasicLayout>
</template>
